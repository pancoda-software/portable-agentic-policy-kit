"""Shared, dependency-free source loading and deterministic rendering."""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROFILES = {"generic", "nuxt-vue"}
GENERATED = ("AGENTS.md", "CLAUDE.md", "ollama-system.txt")
MARKER = "Generated by Portable Agentic Policy Kit"


class PolicyError(ValueError):
    pass


def read_json_yaml(path: Path) -> dict:
    """Read JSON-compatible YAML (YAML 1.2 subset) without PyYAML."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise PolicyError(f"Cannot parse {path}: {exc}") from exc
    if not isinstance(data, dict):
        raise PolicyError(f"Expected object in {path}")
    return data


def project_config(config_path: Path) -> dict:
    data = read_json_yaml(config_path)
    if data.get("schema") != 1:
        raise PolicyError("Project schema must be 1")
    if data.get("profile") not in PROFILES:
        raise PolicyError("Unknown or unsafe project profile")
    if data.get("output_language") not in ("de", "en"):
        raise PolicyError("Supported output_language: de or en")
    name = data.get("project_name")
    if not isinstance(name, str) or re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,63}", name) is None:
        raise PolicyError("project_name must be a safe 1–64-character identifier")
    return data


def render_contents(config_path: Path) -> dict[str, str]:
    config = project_config(config_path)
    version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    profile = config["profile"]
    sources = {
        "version": version,
        "core": (ROOT / "policy" / "core.md").read_text(encoding="utf-8").strip(),
        "profile": (ROOT / "policy" / "profiles" / f"{profile}.md").read_text(encoding="utf-8").strip(),
        "project": json.dumps(config, sort_keys=True, ensure_ascii=False),
    }
    templates = {
        "AGENTS.md": ROOT / "adapters" / "codex" / "AGENTS.md.template",
        "CLAUDE.md": ROOT / "adapters" / "claude" / "CLAUDE.md.template",
        "ollama-system.txt": ROOT / "adapters" / "ollama" / "SYSTEM.prompt.template",
    }
    text_templates = {name: path.read_text(encoding="utf-8") for name, path in templates.items()}
    fingerprint_src = json.dumps({"sources": sources, "templates": text_templates}, sort_keys=True, ensure_ascii=False)
    fingerprint = hashlib.sha256(fingerprint_src.encode("utf-8")).hexdigest()[:16]
    values = {
        "VERSION": version,
        "SOURCE_HASH": fingerprint,
        "PROJECT_NAME": config["project_name"],
        "OUTPUT_LANGUAGE": config["output_language"],
        "CORE_POLICY": sources["core"],
        "PROJECT_PROFILE": sources["profile"],
        "PROFILE_NAME": profile,
    }
    outputs = {}
    for name, template in text_templates.items():
        for key, value in values.items():
            template = template.replace("{{" + key + "}}", value)
        if re.search(r"\{\{[A-Z_]+\}\}", template):
            raise PolicyError(f"Unresolved placeholder in {name}")
        outputs[name] = template.rstrip() + "\n"
    return outputs


def safe_output_directory(out: Path) -> None:
    if out.is_symlink():
        raise PolicyError(f"Refusing symlink output directory: {out}")
    # Existing generated paths must never be symlinks, even when --force is used.
    for name in GENERATED:
        p = out / name
        if p.is_symlink():
            raise PolicyError(f"Refusing symlink generated target: {p}")
