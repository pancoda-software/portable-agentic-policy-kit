#!/usr/bin/env python3
"""Safe, idempotent project setup for the Portable Agentic Policy Kit.

No extra dependencies, network, dependencies, Git writes, or remote actions.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

from common import ROOT, PolicyError, render_contents

BEGIN = "<!-- BEGIN PORTABLE AGENTIC POLICY KIT: MANAGED BLOCK -->"
END = "<!-- END PORTABLE AGENTIC POLICY KIT: MANAGED BLOCK -->"
STATE = Path('.agentic/policy-install.json')
CONFIG = Path('.agentic/project.yaml')
OLLAMA = Path('.agentic/ollama-system.txt')
GATE = Path('.agentic/agent-verify.sh')
VERSION = (ROOT / 'VERSION').read_text(encoding='utf-8').strip()


def checksum(value: str) -> str:
    return hashlib.sha256(value.encode('utf-8')).hexdigest()


def safe_target(root: Path, relative: Path) -> Path:
    """Reject symlinks at every existing component, including directories."""
    p = root
    for part in relative.parts:
        p = p / part
        if p.is_symlink():
            raise PolicyError(f"Symlink targets are not supported: {p}")
    return p


def managed(text: str) -> str:
    return f"{BEGIN}\n{text.rstrip()}\n{END}"


def extract_managed(text: str) -> str | None:
    if BEGIN not in text and END not in text:
        return None
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) >= text.index(END):
        raise PolicyError('Corrupted or duplicated managed markers')
    return text[text.index(BEGIN):text.index(END) + len(END)]


def insert_block(existing: str | None, text: str, prior_hash: str | None, path: Path) -> str:
    block = managed(text)
    if existing is None:
        return block + '\n'
    old = extract_managed(existing)
    if old is not None:
        if prior_hash is None or checksum(old) != prior_hash:
            raise PolicyError(f"Managed section modified or untracked: {path}; manual review required")
        return existing.replace(old, block)
    if prior_hash is not None:
        raise PolicyError(f"Managed section unexpectedly absent: {path}")
    if 'Generated by Portable Agentic Policy Kit' in existing:
        raise PolicyError(f"Legacy generated file needs manual migration: {path}")
    return existing.rstrip('\n') + '\n\n' + block + '\n'


def project_id(project: Path) -> str:
    name = re.sub(r'[^A-Za-z0-9_.-]+', '-', project.name).strip('.-')[:64]
    return name if name and name[0].isalnum() else 'project'


def read_state(path: Path) -> dict:
    if not path.exists():
        return {}
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
    except (ValueError, OSError) as exc:
        raise PolicyError(f"Invalid installation state: {exc}") from exc
    if not isinstance(data, dict) or data.get('schema') != 1 or not isinstance(data.get('managed'), dict):
        raise PolicyError('Invalid install state schema')
    return data


def check_existing(project: Path) -> list[str]:
    state_file = safe_target(project, STATE)
    state = read_state(state_file)
    if not state:
        return ['Policy Kit is not installed in this project']
    problems = []
    for name, digest in state['managed'].items():
        rel = Path(name)
        if rel.is_absolute() or '..' in rel.parts:
            problems.append(f'Invalid stored path: {name}')
            continue
        try:
            file = safe_target(project, rel)
            if not file.is_file():
                problems.append(f'Missing file: {name}')
                continue
            contents = file.read_text(encoding='utf-8')
            marker = extract_managed(contents) if rel.name in ('AGENTS.md','CLAUDE.md') else contents
            if marker is None or checksum(marker) != digest:
                problems.append(f'Drift detected in {name}')
        except (PolicyError, OSError, UnicodeError) as exc:
            problems.append(str(exc))
    if state.get('version') != VERSION:
        problems.append(f"Installed version {state.get('version')} differs from kit {VERSION}")
    return problems


def install(project: Path, language: str = 'de', *, new: bool = False, dry_run: bool = False) -> list[str]:
    project = project.expanduser().absolute()
    if project.is_symlink():
        raise PolicyError(f'Refusing symlink project path: {project}')
    if new and project.exists():
        raise PolicyError(f'New project target already exists: {project}')
    if not new and not project.is_dir():
        raise PolicyError(f'Project directory does not exist: {project}')
    if project.exists() and not os.access(project, os.W_OK):
        raise PolicyError(f'Project is not writable: {project}')

    config_file = safe_target(project, CONFIG)
    state_file = safe_target(project, STATE)
    state = read_state(state_file)
    if state and not config_file.is_file():
        raise PolicyError('Install state exists but project config is missing')
    if config_file.exists():
        from common import project_config, read_json_yaml
        existing_config = read_json_yaml(config_file)
        if existing_config.get('schema') == 1:
            # Explicit, non-destructive migration from v1.1: preserve user notes,
            # remove legacy framework-specific profiles and normalize the schema.
            config = {key: value for key, value in existing_config.items() if key != 'profile'}
            config['schema'] = 2
            if not state or not isinstance(state.get('managed'), dict):
                raise PolicyError('Legacy project requires a valid install state before migration')
        else:
            config = project_config(config_file)
        language = config['output_language']
    else:
        config = {'schema': 2, 'project_name': project_id(project), 'output_language': language}

    if config['output_language'] not in ('de', 'en'):
        raise PolicyError('Language must be de or en')
    # Render from a temporary config, using canonical policy sources.
    with tempfile.TemporaryDirectory(prefix='policy-kit-config-') as td:
        temp_config = Path(td) / 'project.yaml'
        temp_config.write_text(json.dumps(config, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        generated = render_contents(temp_config)

    pending: dict[Path, str] = {}
    config_text = json.dumps(config, indent=2, ensure_ascii=False) + '\n'
    if not config_file.exists() or config_file.read_text(encoding="utf-8") != config_text:
        pending[CONFIG] = config_text

    previous = state.get('managed', {})
    managed_hashes: dict[str, str] = {}
    for name in ('AGENTS.md', 'CLAUDE.md'):
        rel = Path(name)
        target = safe_target(project, rel)
        prior = target.read_text(encoding='utf-8') if target.exists() else None
        if prior is not None and not target.is_file():
            raise PolicyError(f'Not a regular file: {target}')
        content = insert_block(prior, generated[name], previous.get(name), target)
        pending[rel] = content
        section = extract_managed(content)
        assert section is not None
        managed_hashes[name] = checksum(section)

    for rel, source in ((OLLAMA, generated['ollama-system.txt']), (GATE, (ROOT / 'templates/agent-verify.sh').read_text(encoding='utf-8'))):
        target = safe_target(project, rel)
        if target.exists():
            if not target.is_file():
                raise PolicyError(f'Not a regular file: {target}')
            previous_hash = previous.get(rel.as_posix())
            if previous_hash is None:
                raise PolicyError(f'User-owned file exists, refusing overwrite: {target}')
            if checksum(target.read_text(encoding='utf-8')) != previous_hash:
                raise PolicyError(f'Generated file modified, refusing overwrite: {target}')
        pending[rel] = source
        managed_hashes[rel.as_posix()] = checksum(source)

    meta = {'schema': 1, 'version': VERSION, 'managed': managed_hashes}
    pending[STATE] = json.dumps(meta, indent=2, ensure_ascii=False, sort_keys=True) + '\n'
    messages = [f"{('CREATE' if not (project / rel).exists() else 'UPDATE')} {rel.as_posix()}" for rel in pending]
    if dry_run:
        return ['DRY RUN — no files written', *messages]

    # All safety checks above run before any mutation. On failed write, restore prior state.
    originals: dict[Path, bytes | None] = {}
    wrote: list[Path] = []
    try:
        project.mkdir(parents=True, exist_ok=True)
        for rel, content in pending.items():
            target = safe_target(project, rel)
            target.parent.mkdir(parents=True, exist_ok=True)
            originals[target] = target.read_bytes() if target.exists() else None
            fd, tmp_name = tempfile.mkstemp(dir=target.parent, prefix='.agentic-install-')
            try:
                with os.fdopen(fd, 'w', encoding='utf-8') as stream:
                    stream.write(content)
                os.replace(tmp_name, target)
            finally:
                if os.path.exists(tmp_name):
                    os.unlink(tmp_name)
            wrote.append(target)
    except Exception:
        for target in reversed(wrote):
            before = originals[target]
            try:
                if before is None:
                    target.unlink()
                else:
                    target.write_bytes(before)
            except OSError:
                pass
        raise
    return messages


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    dest = ap.add_mutually_exclusive_group()
    dest.add_argument('--project', type=Path, default=None, help='Install in an existing project (default: .)')
    dest.add_argument('--new', type=Path, default=None, help='Create a new, otherwise empty directory with agent policy')
    ap.add_argument('--lang', choices=['de','en'], default='de')
    ap.add_argument('--check', action='store_true', help='Verify installed managed files without modifications')
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()
    target = args.new if args.new is not None else args.project or Path.cwd()
    try:
        if args.check:
            if args.new is not None:
                raise PolicyError('--check requires an existing project')
            errors = check_existing(target.absolute())
            for error in errors:
                print('FAIL',error)
            if errors:
                return 1
            print('PASS: installed managed files match the recorded state')
            return 0
        for message in install(target, args.lang, new=args.new is not None, dry_run=args.dry_run):
            print(message)
        print('Next: review AGENTS.md / CLAUDE.md; configure native sandbox and approval controls separately.')
    except (PolicyError, OSError, UnicodeError, ValueError) as exc:
        print(f'ERROR {exc}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
